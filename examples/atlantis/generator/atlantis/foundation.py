"""Layer 10: the city base under the dome footprint (r <= 606) and temporary safety lighting.

Foundation: solid from y_min+1 to y=0. Deepslate/stone inside; a dark prismarine / polished deepslate band
(r 596..606) around the edge; the y=0 surface is neutral smooth_stone with a polished_andesite ring every 50
blocks (later waves overwrite it with roads, plazas, lagoons).

Temporary light (meta temporary_light=True): invisible light[level=15] blocks at y=1 so that no floor cell is
at block light 0 (hostile mob spawning). Block light falls by 1 per block of Manhattan distance, air does not
block it, so a floor cell at Manhattan distance d from a level-15 source has light 15-d and is lit while d <= 14.
Manhattan balls ("diamonds") of radius R tile the plane perfectly with the lattice generated by (R, R+1) and
(-(R+1), R), one source per 2R^2+2R+1 cells; with R = 14 that is one source per 421 cells (basis (14,15), (-15,14)),
about half the density of a square grid (spacing 15 => 225 cells per source). Near the dome edge sources must
stay >= 2 blocks from the shell, so lattice points beyond that limit are dropped and two rings of sources
(EDGE_RINGS) cover the rim; tests/test_terrain.py proves coverage by brute force over every floor cell.
"""
import math

from .feature import Feature, register
from . import palette as P

BAND_R0, BAND_R1 = 596.0, 606.0
RING_EVERY = 50
LIGHT = P.HIDDEN_LIGHT
LAT_A = (14, 15)
LAT_B = (-15, 14)
LAT_DET = LAT_A[0] * LAT_B[1] - LAT_A[1] * LAT_B[0]          # 421
SHELL_GAP = 2
# (radius offset below the largest valid radius, number of sources on the ring)
EDGE_RINGS = ((0.0, 236), (-12.0, 180))

_cache = {}


def _h(ix, iz, salt=0):
    n = (ix * 374761393 + iz * 668265263 + salt * 2246822519) & 0xFFFFFFFF
    n = ((n ^ (n >> 13)) * 1274126177) & 0xFFFFFFFF
    return (n ^ (n >> 16)) / 4294967295.0


def valid_light(ctx, x, z):
    """A light may sit at (x, 1, z): inside the dome and at least SHELL_GAP blocks from the inner shell."""
    if not ctx.inside_dome(x, 1, z): return False
    d = math.sqrt(x * x + (1 - ctx.dome_cy) ** 2 + z * z)
    return (ctx.dome_R - ctx.dome_thickness) - d >= SHELL_GAP


def _edge_points(ctx):
    key = ('edge', ctx.seed, ctx.dome_radius, ctx.dome_height)
    if key in _cache: return _cache[key]
    r_in = ctx.dome_R - ctx.dome_thickness
    rmax = math.sqrt((r_in - SHELL_GAP) ** 2 - (1 - ctx.dome_cy) ** 2) - 0.5
    pts = set()
    for ri, (off, n) in enumerate(EDGE_RINGS):
        for k in range(n):
            a = 2 * math.pi * (k + 0.5 * (ri % 2)) / n
            x, z = round((rmax + off) * math.cos(a)), round((rmax + off) * math.sin(a))
            if valid_light(ctx, x, z): pts.add((x, z))
    _cache[key] = sorted(pts)
    return _cache[key]


def lattice_points(ctx, x1, z1, x2, z2):
    """Valid lattice sources whose coordinates lie in the rectangle."""
    ax, az = LAT_A; bx, bz = LAT_B
    cs = [((bz * x - bx * z) / LAT_DET, (-az * x + ax * z) / LAT_DET) for x in (x1, x2) for z in (z1, z2)]
    out = []
    for a in range(math.floor(min(c[0] for c in cs)) - 1, math.ceil(max(c[0] for c in cs)) + 2):
        for b in range(math.floor(min(c[1] for c in cs)) - 1, math.ceil(max(c[1] for c in cs)) + 2):
            x, z = a * ax + b * bx, a * az + b * bz
            if x1 <= x <= x2 and z1 <= z <= z2 and valid_light(ctx, x, z): out.append((x, z))
    return out


def light_points(ctx, x1, z1, x2, z2):
    """All temporary light positions (x, z) inside the rectangle (inclusive)."""
    out = lattice_points(ctx, x1, z1, x2, z2)
    out += [p for p in _edge_points(ctx) if x1 <= p[0] <= x2 and z1 <= p[1] <= z2]
    return out


def _floor_material(ctx, x, z, r):
    if r >= BAND_R0:
        return 'polished_deepslate' if _h(x // 2, z // 2, 3) > 0.28 else 'dark_prismarine'
    k = int(r / RING_EVERY + 0.5)
    if k >= 1 and abs(r - k * RING_EVERY) < 0.75: return 'polished_andesite'
    return 'smooth_stone'


def _build_base(vol, ctx):
    c = vol.clip(-607, ctx.y_min + 1, -607, 607, 0, 607)
    if not c: return
    R2 = BAND_R1 * BAND_R1
    y_lo = max(c[1], ctx.y_min + 1)
    for z in range(c[2], c[5] + 1):
        zz = z * z
        for x in range(c[0], c[3] + 1):
            q = x * x + zz
            if q > R2: continue
            r = math.sqrt(q)
            n = _h(x, z, 1)
            if r >= BAND_R0:
                body = 'dark_prismarine' if n < 0.45 else 'polished_deepslate'
            elif n < 0.12:
                body = 'stone'
            else:
                body = 'deepslate'
            if y_lo <= -1:
                vol.fill(x, y_lo, z, x, -1, z, body)
                if r < BAND_R0 and n > 0.85:
                    vol.set(x, -1, z, 'tuff')
            vol.set(x, 0, z, _floor_material(ctx, x, z, r))


def _build_lights(vol, ctx):
    if not (vol.y1 <= 1 <= vol.y2): return
    for x, z in light_points(ctx, vol.x1, vol.z1, vol.x2, vol.z2):
        vol.set(x, 1, z, LIGHT)


def _register(ctx):
    r = int(BAND_R1) + 1
    class Base(Feature):
        def build(self, vol, ctx): _build_base(vol, ctx)
    class Lights(Feature):
        def build(self, vol, ctx): _build_lights(vol, ctx)
    register(Base('foundation_base', (-r, ctx.y_min + 1, -r, r, 0, r), 10, {'kind': 'foundation'}),
             Lights('foundation_temp_lights', (-r, 1, -r, r, 1, r), 10,
                    {'temporary_light': True, 'kind': 'lighting'}))


def _init():
    from . import config
    _register(config.load())


_init()
